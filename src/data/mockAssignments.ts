const NOW = new Date();

function daysFromNow(offset: number, hour = 23, minute = 59): string {
  const d = new Date(NOW);
  d.setDate(d.getDate() + offset);
  d.setHours(hour, minute, 0, 0);
  return d.toISOString();
}

function createdDaysAgo(offset: number): string {
  const d = new Date(NOW);
  d.setDate(d.getDate() + offset);
  return d.toISOString();
}

